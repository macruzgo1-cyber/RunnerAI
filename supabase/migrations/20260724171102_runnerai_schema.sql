  vo2_max numeric NOT NULL DEFAULT 0,
  fatigue_score int NOT NULL DEFAULT 0, -- 0-100
  recovery_score int NOT NULL DEFAULT 50, -- 0-100
  injury_risk risk_level NOT NULL DEFAULT 'low',
  injury_risk_score int NOT NULL DEFAULT 0, -- 0-100
  total_distance_km numeric NOT NULL DEFAULT 0,
  total_workouts int NOT NULL DEFAULT 0,
  weekly_distance_km numeric NOT NULL DEFAULT 0,
  avg_pace_sec_per_km int,
  predicted_5k_sec int,
  predicted_10k_sec int,
  predicted_half_sec int,
  predicted_full_sec int,
  progress_pct numeric NOT NULL DEFAULT 0, -- improvement % vs 4 weeks ago
