/*
# RunnerAI Core Schema

## Overview
Creates the full data model for RunnerAI, an AI running coach. All tables are
owner-scoped (per-user) with Row Level Security. Owner columns default to
auth.uid() so client inserts that omit user_id still satisfy RLS.

## New Tables
1. `profiles` - extended sports profile linked to auth.users (1:1)
2. `workouts` - imported/synced activities (km, pace, hr, cadence, etc.)
3. `training_plans` - AI-generated training plans
4. `plan_sessions` - individual sessions within a plan
5. `ai_messages` - conversation history with the AI coach
6. `achievements` - badges earned by the user
7. `notifications` - smart notifications generated by the AI
8. `user_stats` - latest computed metrics (fatigue, recovery, load, VO2)

## Security
- RLS enabled on every table.
- Each table has 4 owner-scoped policies (select/insert/update/delete).
- Owner column default is auth.uid() everywhere.

## Notes
1. All timestamps are timestamptz with now() default.
2. enums for experience_level and goal_type keep data clean.
3. jsonb columns store flexible AI/metric payloads without schema churn.
4. Indexes on user_id and created_at for common query patterns.
*/

-- Extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ===== ENUMS =====
DO $$ BEGIN
  CREATE TYPE experience_level AS ENUM ('beginner', 'intermediate', 'advanced', 'elite');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE goal_type AS ENUM ('5k','10k','half_marathon','marathon','ultramarathon','weight_loss','endurance');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE risk_level AS ENUM ('low','medium','high');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE plan_status AS ENUM ('active','completed','paused');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE session_status AS ENUM ('pending','completed','skipped','missed');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE notification_type AS ENUM ('recovery','workout','achievement','insight','plan');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ===== PROFILES =====
CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL,
  full_name text,
  avatar_url text,
  age int,
  sex text CHECK (sex IN ('male','female','other')),
  height_cm numeric,
  weight_kg numeric,
  country text,
  city text,
  experience experience_level DEFAULT 'beginner',
  weekly_km numeric DEFAULT 0,
  goal goal_type,
  is_premium boolean NOT NULL DEFAULT false,
  premium_since timestamptz,
  onboarded boolean NOT NULL DEFAULT false,
  total_xp int NOT NULL DEFAULT 0,
  level int NOT NULL DEFAULT 1,
  current_streak int NOT NULL DEFAULT 0,
  longest_streak int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "select_own_profile" ON profiles;
CREATE POLICY "select_own_profile" ON profiles FOR SELECT TO authenticated USING (auth.uid() = id);
DROP POLICY IF EXISTS "insert_own_profile" ON profiles;
CREATE POLICY "insert_own_profile" ON profiles FOR INSERT TO authenticated WITH CHECK (auth.uid() = id);
DROP POLICY IF EXISTS "update_own_profile" ON profiles;
CREATE POLICY "update_own_profile" ON profiles FOR UPDATE TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);
DROP POLICY IF EXISTS "delete_own_profile" ON profiles;
CREATE POLICY "delete_own_profile" ON profiles FOR DELETE TO authenticated USING (auth.uid() = id);

